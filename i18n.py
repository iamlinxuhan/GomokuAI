"""界面多语言。**零 Qt** —— 与 `engine.py` / `engine_local.py` 同一条规矩。

## 为什么键是中文原文

``t("设置")`` 而不是 ``t("settings.title")``。两层理由：

1. **漏译时退化成可读的中文，而不是一串 key。** 表里查不到就原样返回 —— 界面上
   出现的是一条没翻译的中文，用户看得出"这里没翻译"，而不是看到
   ``settings.title`` 这种东西。缺一条不会崩，也不会把界面弄成乱码。
2. **调用点不用起名字。** 五百多条文案逐条起 key，起名成本比翻译本身还高，而且
   改一次中文原文就得同步改 key。

代价是改中文原文等于改 key —— 但原文本来就是用户看得见的东西，改它本来就该
回头看一眼译表。

## 哪些**不**翻译

日志文件（`gamelog.py` 写进 `game_log_*.txt` 的那些）与引擎回报的 ``reason``
（``PVS搜索`` / ``开局库`` / ``Python (本地)``）保持中文。它们是**诊断产物**：
``README``、推广文章和已发布的 bug 报告都在逐字引用这些字符串，翻译会让历史日志
与文档对不上。界面语言与日志语言分开是常见做法，不是遗漏。

## 系统语言从哪来

``QLocale.system().name()`` 由界面层取好传进 ``set_system_locale()`` —— 这样本
模块不必导入 Qt，``server.py`` / ``tools/bench.py`` 那些无头程序导入它也不会有
额外代价（它们其实用不上，但只要不引 Qt 就无所谓）。
"""

