def _normalize(locale: str) -> str:
    """把 ``QLocale.system().name()`` 那种 ``zh_CN`` / ``en_GB`` 映射到我们的代码。

    认不出来的语言回落到英语 —— 界面是给不认识中文的人准备的，落到中文等于没做。
    繁体要按**地区**判：``zh_TW`` / ``zh_HK`` / ``zh_MO`` 是繁體，``zh_CN`` /
    ``zh_SG`` 与裸 ``zh`` 是简体。
    """
    low = (locale or "").replace("-", "_").lower()
    if not low:
        return DEFAULT
    head, _, tail = low.partition("_")
    if head == "zh":
        return "zh-TW" if tail in ("tw", "hk", "mo") else "zh-CN"
    if head in ("en",):
        return "en"
    if head == "ru":
        return "ru"
    if head == "ja":
        return "ja"
    if head == "ko":
        return "ko"
    return "en"


def set_system_locale(locale: str) -> None:
    """由界面层传入 ``QLocale.system().name()``。"""
    global _system_locale
    _system_locale = locale or ""
    _resolve()


def language() -> str:
    """用户**选的**那一个（可能是 ``SYSTEM``）。"""
    return _choice


def resolved() -> str:
    """真正生效的语言代码。"""
    return _lang


def set_language(choice: str) -> None:
    """设定选择。非法值按"跟随系统"处理 —— 与其抛异常让界面开不了，不如回退。"""
    global _choice
    _choice = choice if choice in CHOICES else SYSTEM
    _resolve()


def _resolve() -> None:
    global _lang
    if _choice == SYSTEM:
        _lang = _normalize(_system_locale) if _system_locale else DEFAULT
    else:
        _lang = _choice


