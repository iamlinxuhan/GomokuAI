#: ``{语言代码: {该语言的译文}}``，用来认"这条已经翻好了"（见 ``t()``）。
_VALUES: dict = {}

#: 中文表意文字。用来判"这条到底是不是待翻译的界面文案"（见 ``_note_miss``）。
_CJK = re.compile(r"[㐀-䶿一-鿿豈-﫿]")


class _Done(str):
    """**已经翻过**的一串文字。

    界面里有大量"调用方先 ``tf()`` 翻好一条带 %d 的模板，再交给 ``faint_label``
    这一类工厂"的写法，而工厂自己也会过一遍 ``t()``。第二次查找必然落空 —— 结果
    虽然对（原样返回），漏译盘点里却会多出一条误报，把真正没翻的淹掉。

    标一下就能一次性解决：``t()`` 见到标记立刻放行。用 ``str`` 子类而不是另建
    包装类型，是为了让返回值照样能进 ``QLabel``、能 ``%``、能 ``==`` 比较。
    """

    __slots__ = ()


def _translated_values(lang: str) -> frozenset:
    """某语言的全部**整条**译文，惰性算一次。

    配合 ``_Done`` 兜住另一种情形：一条**不带占位符**的译文被交回来第二次 —— 标
    记链断了（存进 QSettings、拼进别的串再取回来），但整条译文比对仍能认出它。

    注意它**兜不住带占位符的那一类**：``"Move %d   %s"`` 与格式化成品
    ``"Move 2   白棋"`` 永远不相等。那一类只能靠 ``tf()`` 自己把 ``_Done`` 补回来
    （见 ``tf`` 的文档串与 ``tests/test_i18n.py`` 里那条用例）。
    """
    got = _VALUES.get(lang)
    if got is None:
        got = frozenset((_STRINGS.get(lang) or {}).values())
        _VALUES[lang] = got
    return got


def t(text: str) -> str:
    """把一条界面文案翻成当前语言。查不到（或已经是译文）就原样返回。"""
    if isinstance(text, _Done):
        return text
    if _lang == "zh-CN":
        return text
    table = _STRINGS.get(_lang)
    got = table.get(text) if table else None
    if got is not None:
        return _Done(got)
    if text in _translated_values(_lang):
        return _Done(text)
    _note_miss(text, _lang)
    return text


def tf(fmt: str, *args) -> str:
    """``t()`` + ``%`` 一步到位，给 ``t("第 %d 手") % n`` 那种写法用。

    结果照样打上 ``_Done`` —— ``%`` 会把子类降回 ``str``，不补一下标记就断了。
    模板本身在 ``t()`` 里已经查过一遍，格式化后的成品不必再查。
    """
    return _Done(t(fmt) % args)


def language_label() -> str:
    """设置里那一行的标签，跟随当前界面语言。"""
    return LANGUAGE_LABEL.get(_lang, LANGUAGE_LABEL[DEFAULT])


def follow_system_label() -> str:
    """「跟随系统」选项的文案，跟随当前界面语言。"""
    return FOLLOW_SYSTEM.get(_lang, FOLLOW_SYSTEM[DEFAULT])


def language_hint() -> str:
    return LANGUAGE_HINT.get(_lang, LANGUAGE_HINT[DEFAULT])


def language_name(code: str) -> str:
    """某个语言选项按钮上的文字（各语言的自名，不随界面语言变）。"""
    if code == SYSTEM:
        return follow_system_label()
    return LANGUAGE_NAME.get(code, code)


# ---------------------------------------------------------------------------
# 漏译盘点
# ---------------------------------------------------------------------------
# 用来**从实际运行的界面里**收出"哪些中文被真的显示过"，而不是靠人肉通读源码
# 猜哪些字符串用户看得见。跑一遍冒烟测试 + 截图工具，``t()`` 查不到的那些就是
# 待翻译清单 —— 源码里躺着但从没被显示过的（断言消息、日志模板、QSS 块）自然
# 不会出现。见 ``tools/i18n_misses.py``。


def enable_miss_log() -> None:
    """开始记录漏译。只在盘点时开，正常运行不记（省内存也省得误导）。"""
    global _misses
    _misses = set()


def miss_log() -> list:
    """按中文原文排序的漏译清单。没开盘点则返回空表。"""
    return sorted(_misses) if _misses else []


def _note_miss(text: str, lang: str) -> None:
    if _misses is None:
        return
    # 一个汉字都没有的串不是"没翻的文案"，是**数据** —— 计时的 "00:00"、占位符
    # "—"、齿轮的 "⚙"、盘面坐标、还有本来就不该翻的 "Gomoku AI" / "AI" 之类。
    # 它们每一次刷新都会路过 t()，不滤掉的话盘点会被埋掉。
    if not _CJK.search(text):
        return
    _misses.add(text)
